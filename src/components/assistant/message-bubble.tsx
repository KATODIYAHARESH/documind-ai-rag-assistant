"use client";

import { useState } from "react";
import { motion } from "framer-motion";
import { AlertTriangle, Check, Copy, RotateCcw } from "lucide-react";
import { formatDuration, tw } from "@/lib/format";
import { useToast } from "@/context/toast";
import { Button } from "@/components/ui/button";
import { LogoMark } from "@/components/ui/logo";
import { Markdown } from "./markdown";
import type { UIMessage } from "./types";

export function TypingDots({ label = "Searching your documents…" }: { label?: string }) {
  return (
    <span className="flex items-center gap-1.5 py-1" role="status" aria-label="Assistant is working">
      <span className="h-2 w-2 animate-typing rounded-full bg-crimson-400" />
      <span className="h-2 w-2 animate-typing rounded-full bg-crimson-400 [animation-delay:0.15s]" />
      <span className="h-2 w-2 animate-typing rounded-full bg-crimson-400 [animation-delay:0.3s]" />
      <span className="ml-2 text-xs text-neutral-500">{label}</span>
    </span>
  );
}

/** Honest labelling of how an answer was produced. */
export function ModeBadge({ mode, model }: { mode: string | null | undefined; model: string | null | undefined }) {
  const base =
    "inline-flex max-w-full items-center truncate rounded-full border px-2 py-0.5 text-[11px] font-medium leading-5";
  if (mode === "generative") {
    return (
      <span title={`Generated by ${model ?? "the configured model"} strictly from the retrieved passages`} className={tw(base, "border-white/10 bg-white/[0.05] text-neutral-300")}>
        Generated{model ? ` · ${model}` : ""}
      </span>
    );
  }
  if (mode === "extractive") {
    return (
      <span
        title="No LLM API key is configured on this server. These are the most relevant sentences from your documents, quoted verbatim."
        className={tw(base, "border-crimson-600/35 bg-crimson-900/35 text-crimson-300")}
      >
        Extractive · offline
      </span>
    );
  }
  if (mode === "not-found") {
    return <span className={tw(base, "border-white/10 bg-white/[0.04] text-neutral-400")}>No matching passage</span>;
  }
  if (mode === "interrupted") {
    return <span className={tw(base, "border-white/10 bg-white/[0.04] text-neutral-400")}>Stopped</span>;
  }
  return null;
}

interface MessageBubbleProps {
  message: UIMessage;
  isLast: boolean;
  busy: boolean;
  canRegenerate: boolean;
  onRegenerate: () => void;
  onCitation: (tag: string) => void;
}

export function MessageBubble({ message, isLast, busy, canRegenerate, onRegenerate, onCitation }: MessageBubbleProps) {
  const { toast } = useToast();
  const [copied, setCopied] = useState(false);
  const isUser = message.role === "user";

  const copy = async () => {
    try {
      await navigator.clipboard.writeText(message.content.replace(/\s?\[S\d+\]/g, ""));
      setCopied(true);
      window.setTimeout(() => setCopied(false), 1600);
    } catch {
      toast({ variant: "error", title: "Copy failed", description: "Your browser blocked clipboard access." });
    }
  };

  return (
    <motion.article
      initial={{ opacity: 0, y: 12 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ duration: 0.28, ease: "easeOut" }}
      className={tw("flex w-full gap-3", isUser ? "justify-end" : "justify-start sm:gap-4")}
      aria-label={isUser ? "Your question" : "DocuMind answer"}
    >
      {!isUser ? (
        <span className="glass mt-0.5 flex h-8 w-8 shrink-0 items-center justify-center rounded-xl">
          <LogoMark className="h-5 w-5" />
        </span>
      ) : null}

      <div className={tw("min-w-0 max-w-[min(100%,780px)]", isUser && "flex flex-col items-end")}>
        {isUser ? (
          <div className="whitespace-pre-wrap break-words rounded-2xl rounded-br-md border border-crimson-700/40 bg-linear-to-br from-crimson-900/75 to-crimson-950/70 px-4 py-3 text-[15px] leading-relaxed text-white shadow-[0_10px_30px_-16px_rgba(139,0,0,0.9)]">
            {message.content}
          </div>
        ) : message.pending ? (
          <div className="glass rounded-2xl rounded-tl-md px-4 py-3.5">
            <TypingDots />
          </div>
        ) : (
          <>
            <div className="glass rounded-2xl rounded-tl-md px-4 py-3.5">
              {message.error ? (
                <div className="flex flex-col items-start gap-3">
                  <div className="flex items-start gap-2.5 rounded-xl border border-crimson-700/40 bg-crimson-950/50 px-3.5 py-3">
                    <AlertTriangle className="mt-0.5 h-4 w-4 shrink-0 text-crimson-400" />
                    <div>
                      <p className="text-sm font-medium text-white">The answer couldn&apos;t be generated.</p>
                      <p className="mt-1 text-xs leading-relaxed text-neutral-400">{message.error}</p>
                    </div>
                  </div>
                  {canRegenerate ? (
                    <Button size="sm" variant="secondary" loading={busy} onClick={onRegenerate} icon={<RotateCcw className="h-3.5 w-3.5" />}>
                      Try again
                    </Button>
                  ) : null}
                </div>
              ) : (
                <>
                  <Markdown text={message.content} onCitation={onCitation} />
                  {message.streaming ? (
                    <span className="ml-0.5 inline-block h-4 w-[2px] translate-y-0.5 animate-pulse bg-crimson-400" aria-hidden />
                  ) : null}
                </>
              )}
            </div>

            {!message.streaming && !message.error ? (
              <div className="mt-1.5 flex flex-wrap items-center gap-2 pl-1">
                <ModeBadge mode={message.mode} model={message.model} />
                {message.latencyMs ? (
                  <span className="text-[11px] text-neutral-600">{formatDuration(message.latencyMs)}</span>
                ) : null}
                <span className="ml-auto flex items-center gap-0.5">
                  <button
                    type="button"
                    onClick={() => void copy()}
                    aria-label="Copy answer"
                    title="Copy answer"
                    className="flex h-7 w-7 items-center justify-center rounded-lg text-neutral-500 transition hover:bg-white/10 hover:text-white focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-crimson-400/60"
                  >
                    {copied ? <Check className="h-3.5 w-3.5 text-crimson-300" /> : <Copy className="h-3.5 w-3.5" />}
                  </button>
                  {isLast && message.mode !== "interrupted" ? (
                    <button
                      type="button"
                      onClick={onRegenerate}
                      disabled={!canRegenerate}
                      aria-label="Regenerate answer"
                      title="Regenerate answer"
                      className="flex h-7 w-7 items-center justify-center rounded-lg text-neutral-500 transition hover:bg-white/10 hover:text-white focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-crimson-400/60 disabled:opacity-40"
                    >
                      <RotateCcw className={tw("h-3.5 w-3.5", busy && "animate-spin")} />
                    </button>
                  ) : null}
                </span>
              </div>
            ) : null}
          </>
        )}
      </div>
    </motion.article>
  );
}
